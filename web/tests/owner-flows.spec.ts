test("Memory edits notes, restores revisions, and shows Git backup", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/memory")
  const backup = page.getByRole("region", { name: "Git backup" })
  await expect(backup.getByLabel("Repository")).toHaveValue(/^file:\/\//)
  await expect(backup.getByLabel("Branch")).toHaveValue("main")
  await expect(backup.getByLabel("Author name")).toHaveValue("Fixture Owner")
  await expect(backup.getByLabel("Author email")).toHaveValue("owner@example.test")
  await expect(backup.getByLabel("Credential")).toHaveAttribute("type", "password")
  await expect(backup.getByRole("status")).toContainText("Last backup")
  await backup.getByRole("button", { name: "Restore from repository" }).click()
  const confirmBackup = page.getByRole("alertdialog", { name: "Restore from repository?" })
  await expect(confirmBackup).toBeVisible()
  await confirmBackup.getByRole("button", { name: "Cancel" }).click()
  await expect(confirmBackup).toBeHidden()
  const started = page.waitForResponse((response) => response.request().method() === "POST"
    && new URL(response.url()).pathname === "/api/memory/backup/now")
  await backup.getByRole("button", { name: "Back up now" }).click()
  expect((await started).ok()).toBe(true)
  await backup.getByRole("button", { name: "Restore from repository" }).click()
  await confirmBackup.getByRole("button", { name: "Restore", exact: true }).click()
  await expect(page.getByText("Repository restore complete.")).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)

  await page.getByRole("button", { name: "review-checklist", exact: true }).click()
  const note = page.getByRole("dialog")
  const edit = note.getByRole("button", { name: "Edit", exact: true })
  await expect(note.getByText("/memories/general/notes/review-checklist.md")).toBeVisible()
  await expect(note.getByText("Created by")).toBeVisible()
  await edit.click()
  const title = note.getByRole("textbox", { name: "Title" })
  const body = note.getByRole("textbox", { name: "Body" })
  await expect(title).toBeFocused()
  await body.fill("Discard this draft.")
  await note.getByRole("button", { name: "Cancel" }).click()
  await expect(edit).toBeFocused()
  await expect(note.getByText("Review the change.", { exact: true })).toBeVisible()
  await edit.click()
  await title.fill("Updated checklist")
  await body.fill("Review the change and sign off.")
  await note.getByRole("button", { name: "Save", exact: true }).click()
  await expect(note.getByRole("heading", { name: "Updated checklist" })).toBeVisible()
  await expect(note.getByText("Review the change and sign off.", { exact: true })).toBeVisible()
  await expect(note.getByText("release", { exact: true })).toBeVisible()

  await note.getByText("History", { exact: true }).click()
  const revisions = note.getByRole("listitem")
  await expect(revisions).toHaveCount(2)
  await expect(revisions.first()).toContainText("edit")
  await expect(revisions.first()).toContainText("Owner")
  await revisions.last().getByRole("button", { name: "Restore", exact: true }).click()
  const confirm = note.getByRole("form", { name: "Confirm restore" })
  await expect(confirm).toBeFocused()
  await confirm.getByRole("button", { name: "Restore revision" }).click()
  await expect(note.getByRole("heading", { name: "Review checklist" })).toBeVisible()
  await expect(note.getByText("Review the change.", { exact: true })).toBeVisible()
  await expect(revisions).toHaveCount(3)
  await expect(revisions.first()).toContainText("restore")
})

test("Memory changes sync and restores an exported archive", async ({ page }) => {
  await page.goto("/memory")
  const sync = page.getByRole("switch", { name: "Memory sync" })
  await expect(sync).toBeEnabled()
  const checked = await sync.getAttribute("aria-checked")
  await sync.click()
  await expect(sync).toHaveAttribute("aria-checked", checked === "true" ? "false" : "true")
  await page.reload()
  await expect(sync).toHaveAttribute("aria-checked", checked === "true" ? "false" : "true")

  const download = page.waitForEvent("download")
  await page.getByRole("button", { name: "Download", exact: true }).click()
  const archive = await download
  expect(archive.suggestedFilename()).toMatch(/^swb-memory-\d{8}\.zip$/)
  await page.getByLabel("Memory archive").setInputFiles(await archive.path())
  await expect(page.getByRole("region", { name: "Memory controls" }).getByRole("status"))
    .toHaveText("3 unchanged")
})

test("Memory saves a masked credential and shows only its saved state", async ({ page }) => {
  await page.goto("/memory")
  const backup = page.getByRole("region", { name: "Git backup" })
  await backup.getByLabel("Automatic backup").uncheck()
  await backup.getByLabel("Repository").fill("https://example.test/memory.git")
  const credential = backup.getByLabel("Credential")
  const fixture = "fixture-backup-token"
  await credential.fill(fixture)
  const saved = page.waitForResponse((response) => response.request().method() === "POST"
    && new URL(response.url()).pathname === "/api/memory/backup")
  await backup.getByRole("button", { name: "Save", exact: true }).click()
  const response = await saved
  expect(response.ok()).toBe(true)
  expect(await response.text()).not.toContain(fixture)
  await expect(credential).toHaveValue("")
  await expect(credential).toHaveAttribute("placeholder", "Saved")
  await page.reload()
  await expect(credential).toHaveValue("")
  await expect(credential).toHaveAttribute("placeholder", "Saved")
})

